// Build the unified Star Suite installer (pet + dream skin in ONE Electron instance) from this sanitized checkout.
const fs=require('node:fs'),path=require('node:path'),{execFileSync}=require('node:child_process');
const {detectWebCompanion}=require('./web-companion-path.cjs');
const root=path.resolve(__dirname,'..'),version=require('../package.json').version;
const out=path.join(root,'dist/installers'),stage=path.join(root,'dist/installer-stage-'+Date.now());
const runtime=path.dirname(require('electron')),csc=path.join(process.env.WINDIR,'Microsoft.NET/Framework64/v4.0.30319/csc.exe');
fs.mkdirSync(out,{recursive:true});fs.mkdirSync(stage,{recursive:true});
// 版本号随 package.json 注入编译单元，安装器注册表不再写死旧版本。
const versionSource=path.join(stage,'GeneratedVersion.cs');
fs.writeFileSync(versionSource,`// Generated by tools/build-installers.cjs — do not edit.\ninternal static partial class StartupSettings { public const string BuildVersion=${JSON.stringify(version)}; }\n`);

const dir=stage,app=path.join(dir,'resources/app');
fs.cpSync(runtime,dir,{recursive:true,filter:f=>path.basename(f)!=='default_app.asar'});
fs.renameSync(path.join(dir,'electron.exe'),path.join(dir,'StarSuite.exe'));
fs.mkdirSync(app,{recursive:true});
for(const name of ['shared','LICENSE','NOTICE.md','ASSETS.md'])fs.cpSync(path.join(root,name),path.join(app,name),{recursive:true});
for(const project of ['Antigravity-Cat-Widget','Antigravity-Dream-Skin']){
 // 统一负载：挂件主进程直接引用皮肤域模块，两个项目的 src/assets 都必须进包。
 for(const name of ['src','assets'])fs.cpSync(path.join(root,project,name),path.join(app,project,name),{recursive:true});
 if(fs.existsSync(path.join(app,project,'assets/references')))throw Error('Reference images must not enter installer');
}
fs.writeFileSync(path.join(app,'package.json'),JSON.stringify({name:'star-suite',version,main:'Antigravity-Cat-Widget/src/main/index.cjs'}));

const common=['/nologo','/target:winexe','/optimize+','/r:System.Windows.Forms.dll','/r:System.Drawing.dll','/r:Microsoft.CSharp.dll','/define:SUITE'];
const sources=path.join(__dirname,'installer'),icon=path.join(app,'Antigravity-Cat-Widget/assets/app-icon.ico');
execFileSync(csc,[...common,'/win32icon:'+icon,'/out:'+path.join(dir,'StartupSettings.exe'),path.join(sources,'StartupSettings.cs'),versionSource],{stdio:'inherit'});
execFileSync(csc,['/nologo','/target:exe','/optimize+','/out:'+path.join(app,'Antigravity-Cat-Widget/src/native/ForegroundHost.exe'),path.join(app,'Antigravity-Cat-Widget/src/native/ForegroundHost.cs')],{stdio:'inherit'});

// 开始菜单三项的表情图标：默认(idle) / 得意(proud-v3) / 委屈(sad-v3)。
(async()=>{
 const sharp=require('sharp');
 const frames=path.join(app,'Antigravity-Cat-Widget/assets/character-packs/gemini-star-v1/frames');
 const iconsDir=path.join(dir,'icons');fs.mkdirSync(iconsDir,{recursive:true});
 const makeIcon=async(png,outPath)=>{
  const sizes=[256,64,48,32,16];
  const blobs=await Promise.all(sizes.map(size=>sharp(path.join(frames,png)).resize(size,size,{fit:'contain',background:{r:0,g:0,b:0,alpha:0}}).png().toBuffer()));
  const header=Buffer.alloc(6);header.writeUInt16LE(0,0);header.writeUInt16LE(1,2);header.writeUInt16LE(sizes.length,4);
  const entries=[];let offset=6+16*sizes.length;
  blobs.forEach((blob,i)=>{const entry=Buffer.alloc(16);const size=sizes[i];entry[0]=size>=256?0:size;entry[1]=size>=256?0:size;entry.writeUInt16LE(1,4);entry.writeUInt16LE(32,6);entry.writeUInt32LE(blob.length,8);entry.writeUInt32LE(offset,12);offset+=blob.length;entries.push(entry);});
  fs.writeFileSync(outPath,Buffer.concat([header,...entries,...blobs]));
 };
 await makeIcon('idle.png',path.join(iconsDir,'launch.ico'));
 await makeIcon('proud-v3.png',path.join(iconsDir,'settings.ico'));
 await makeIcon('sad-v3.png',path.join(iconsDir,'uninstall.ico'));

 // 换掉 StarSuite.exe 的 Electron 默认图标（零依赖 PE 资源替换）。
 const iconSwapExe=path.join(stage,'IconSwap.exe');
 execFileSync(csc,['/nologo','/target:exe','/optimize+','/out:'+iconSwapExe,path.join(sources,'IconSwap.cs')],{stdio:'inherit'});
 execFileSync(iconSwapExe,[path.join(dir,'StarSuite.exe'),icon],{stdio:'inherit'});

 // Inno Setup 组件化安装（core 必装 / webext 可选档位 1）：标记文件 + Web 插件指引 + ISCC 编译。
 fs.writeFileSync(path.join(dir,'.starsuite-install'),'Suite\n');
 fs.copyFileSync(path.join(sources,'web-plugin-guide.html'),path.join(dir,'web-plugin-guide.html'));
 const iscc=path.join(__dirname,'vendor/InnoSetup/ISCC.exe');
 if(!fs.existsSync(iscc))throw Error('未找到 Inno Setup 编译器（tools/vendor/InnoSetup/ISCC.exe）——请先运行 tools/ensure-inno.cjs 一次性下载。');
 // web 端组件：分房后优先从 web worktree 现场构建最新插件，再随 webext 组件进包。
 const web=detectWebCompanion();
 let webExtReady=false;
 if(web){
  try{execFileSync(process.execPath,[path.join(web.base,'scripts','build.js')],{stdio:'inherit',cwd:web.base,timeout:300000});}
  catch(error){console.warn('web 插件构建失败，webext 组件将只含安装指引：',error.message);}
  webExtReady=fs.existsSync(path.join(web.dist,'kimino-gemini-companion.xpi'))&&fs.existsSync(path.join(web.dist,'kimino-gemini-companion-edge-chrome.zip'));
 }else console.warn('未找到 web 端工作目录（../Catstella-web 或 WEB_COMPANION_PATH），webext 组件将只含安装指引');
 const target=path.join(out,'Catstella-Setup-'+version+'-x64.exe');
 fs.rmSync(target,{force:true});
 const isccArgs=['/DAppVersion='+version,'/DStageDir='+stage,'/DOutputDir='+out];
 if(webExtReady)isccArgs.push('/DWebExtFiles='+web.dist);
 execFileSync(iscc,isccArgs.concat(path.join(sources,'star-suite.iss')),{stdio:'inherit'});
 console.log(target);
})().catch(error=>{console.error(error);process.exitCode=1;});
